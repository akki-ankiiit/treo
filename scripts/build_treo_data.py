#!/usr/bin/env python3
"""Generate src/data/treo-projects.ts from the scraper output.

Inputs:  scripts/data/treo-source.json, public/assets/treo/asset-manifest.json
Output:  src/data/treo-projects.ts

Only verified fields from the official project pages are emitted (address,
location, status, architect, interior designer). No descriptions, budgets or
square footage are invented.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
source = json.loads((ROOT / "scripts/data/treo-source.json").read_text())
manifest = json.loads((ROOT / "public/assets/treo/asset-manifest.json").read_text())
files = {a["local_file"]: a for a in manifest["assets"] if a["download_status"] == "downloaded"}

# Projects highlighted in the brief appear first on the homepage (official portfolio order).
FEATURED = [
    "255 Ocean Blvd", "1745 W 24 St", "138 South Island Drive", "5515 Pine Tree Dr",
    "1727 W 24 Street", "1051 S Northlake Dr", "401 Ocean Blvd", "1015 S Southlake Drive",
    "1260 100th St", "125 Ocean Blvd", "215 Ocean Blvd", "7801 Atlantic Way",
    "9520 W Broadview Dr", "555 Sabal Palm Dr", "407 Golden Beach Dr", "1175 Killian Park Rd",
    "84 Bal Bay Drive", "478 Tamarind Dr",
]


def slugify(t):
    return re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", t.lower())).strip("-")


def tidy(name):
    return name.replace("_", " ").strip() if name else None


projects = []
for p in sorted(source["projects"].values(), key=lambda p: p["order"]):
    if not p["images"]:
        continue
    images = []
    for i, f in enumerate(p["images"]):
        a = files.get(f)
        if not a:
            continue
        images.append({
            "src": f,
            "width": a["width"],
            "height": a["height"],
            "alt": f"{p['name']}, {p['location']} — residence by TREO Construction"
                   + ("" if i == 0 else f", view {i + 1}"),
        })
    projects.append({
        "slug": slugify(f"{p['name']} {p['location']}"),
        "name": p["name"],
        "location": p["location"],
        "locationKey": slugify(p["location"]),
        "locationFull": (p.get("location_full") or f"{p['location']}, Florida").replace("FLorida", "Florida"),
        "status": p.get("status") or "Completed",
        "statusLabel": p.get("status_label") or p.get("status") or "Completed",
        "architect": tidy(p.get("architect")),
        "interiors": tidy(p.get("interiors")),
        "featured": p["name"] in FEATURED,
        "sourceUrl": p["url"],
        "cover": images[0],
        "gallery": images,
    })

for i, p in enumerate(projects):
    p["number"] = f"{i + 1:02d}"

header = '''/**
 * TREO Construction portfolio — generated by scripts/build_treo_data.py from the
 * official portfolio (https://www.treoconstruction.com/portfolio/).
 * Do not edit by hand; re-run the scraper and this builder instead.
 */
export type ProjectImage = { src: string; width: number; height: number; alt: string };
export type Project = {
  slug: string;
  number: string;
  name: string;
  location: string;
  locationKey: string;
  locationFull: string;
  status: "Completed" | "Active";
  statusLabel: string;
  architect: string | null;
  interiors: string | null;
  featured: boolean;
  sourceUrl: string;
  cover: ProjectImage;
  gallery: ProjectImage[];
};

'''
body = "export const projects: Project[] = " + json.dumps(projects, indent=2, ensure_ascii=False) + ";\n"
body += '''
export const projectBySlug = (slug: string) => projects.find((p) => p.slug === slug);
export const projectByName = (name: string) => projects.find((p) => p.name === name);
export const statusOptions = [
  { value: "*", label: "All projects" },
  { value: "completed", label: "Completed" },
  { value: "active", label: "Active" },
];
export const locationOptions = [
  { value: "*", label: "All locations" },
  ...[...new Set(projects.map((p) => p.location))]
    .sort((a, b) => projects.filter((p) => p.location === b).length - projects.filter((p) => p.location === a).length)
    .map((location) => ({ value: projects.find((p) => p.location === location)!.locationKey, label: location })),
];
'''
(ROOT / "src/data/treo-projects.ts").write_text(header + body)
print(f"{len(projects)} projects, {sum(len(p['gallery']) for p in projects)} images")

# --- Brand assets derived from the official logo (no redrawing) -------------
# Monochrome alpha masks let the authentic logo inherit the site's existing
# colour themes via CSS `mask-image` + `currentColor`.
from PIL import Image  # noqa: E402

logo_dir = ROOT / "public/assets/treo/logo"
src = Image.open(logo_dir / "treo-logoheader-light.png").convert("RGBA")
alpha = src.split()[3]


def mask(box, name, scale=4):
    a = alpha.crop(box)
    a = a.resize((a.width * scale, a.height * scale), Image.LANCZOS)
    out = Image.new("RGBA", a.size, (255, 255, 255, 0))
    out.putalpha(a)
    out.save(logo_dir / name, optimize=True)
    return out


mask((23, 0, 200, 60), "treo-logo-mark-mask.png")          # "TREO"
mask((23, 0, 478, 60), "treo-logo-full-mask.png")          # "TREO | CONSTRUCTION"

# Favicon / social icon: official mark on the site's existing navy theme colour.
mark = alpha.crop((23, 0, 200, 60))
for size, name in ((64, "favicon-64.png"), (180, "apple-touch-icon.png"), (512, "icon-512.png")):
    icon = Image.new("RGBA", (size, size), (23, 35, 59, 255))
    w = int(size * 0.78)
    h = round(mark.height * w / mark.width)
    m = mark.resize((w, h), Image.LANCZOS)
    icon.paste(Image.new("RGBA", m.size, (255, 255, 255, 255)), ((size - w) // 2, (size - h) // 2), m)
    icon.save(ROOT / "public" / name, optimize=True)
print("brand masks and icons written")
